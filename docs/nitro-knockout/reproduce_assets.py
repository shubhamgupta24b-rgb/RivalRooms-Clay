def digest(data):
    return hashlib.sha256(data).hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def replace_once(text, before, after, label):
    count = text.count(before)
    require(count == 1, f"{label}: expected one match, found {count}")
    return text.replace(before, after, 1)


def adapt(name, original):
    if name.endswith(".css"):
        return original
    text = original.decode("utf-8").replace("\r\n", "\n")
    if name.endswith(".js"):
        for label, before, after in JS_EDITS:
            text = replace_once(text, before, after, label)
    else:
        text = replace_once(text, 'type="module" crossorigin', 'defer', "H1: local classic script")
        text = replace_once(text, 'rel="stylesheet" crossorigin', 'rel="stylesheet"', "H2: local CSS")
        script = '    <script defer src="./assets/index-CejRMBG2.js"></script>'
        text = replace_once(text, script, ERROR_BRIDGE + script, "H3: engine error reporting")
    # Preserve the actual Windows checkout's CRLF conversion, including its
    # byte-hash identity. CSS was copied verbatim and does not undergo this step.
    return text.replace("\n", "\r\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="The unmodified supplied ZIP")
    parser.add_argument("--output", type=Path, help="A new, not-yet-existing destination directory")
    args = parser.parse_args()
    require(digest(args.archive.read_bytes()) == ZIP_SHA256, "Archive SHA-256 mismatch; no extraction performed")
    generated = {}
    with zipfile.ZipFile(args.archive) as archive:
        for name, (source_hash, output_hash) in ASSETS.items():
            original = archive.read("repo/mobile/assets/nitro/" + name)
            require(digest(original) == source_hash, f"Supplied member hash mismatch: {name}")
            result = adapt(name, original)
            require(digest(result) == output_hash, f"Adapted hash mismatch: {name}; recipe is not complete")
            generated[name] = result
    if args.output:
        # Do not allow an existing directory, even if it appears empty.
        args.output.mkdir(parents=True, exist_ok=False)
        for name, data in generated.items():
            path = args.output / name
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("xb") as output:
                output.write(data)
            print(f"WROTE {digest(data)} {path}")
    else:
        current = Path(__file__).resolve().parents[2] / "mobile/assets/nitro"
        for name, data in generated.items():
            require((current / name).read_bytes() == data, f"Checkout differs from generated bytes: {name}")
            print(f"MATCH {digest(data)} {name}")
    print("PASS pinned archive, ten exact JS edits, three HTML edits, CRLF identity, unchanged CSS; original untouched")


if __name__ == "__main__":
    main()
